USE auxiliares;
DELIMITER //
BEGIN NOT ATOMIC
  DECLARE n INT DEFAULT 0;
  DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;
  IF COALESCE(@tp_roles_v1_approved,0)<>1 OR DATABASE()<>'auxiliares' OR VERSION() NOT LIKE '11.8.9-MariaDB%' THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Autorizacion, base o version no confirmada';
  END IF;
  SELECT COUNT(*) INTO n FROM information_schema.TABLES WHERE TABLE_SCHEMA='auxiliares' AND TABLE_NAME IN
    ('FB_USUARIOS','FB_USUARIOS_CREDENCIALES','FB_USUARIOS_SESIONES','FB_LOGIN_INTENTOS','FB_SECURITY_STANDALONE_V1','FB_CIU_CONSULTAS_WEB','FB_CONSULTAS_HISTORIAL') AND ENGINE='InnoDB';
  IF n<>7 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Preflight: faltan tablas InnoDB'; END IF;
  SELECT COUNT(*) INTO n FROM information_schema.COLUMNS WHERE TABLE_SCHEMA='auxiliares' AND TABLE_NAME='FB_USUARIOS' AND
    ((COLUMN_NAME='USER_ID' AND COLUMN_TYPE='char(36)' AND COLUMN_KEY='PRI') OR
     (COLUMN_NAME='USERNAME' AND COLUMN_TYPE='varchar(100)') OR
     (COLUMN_NAME='ROLE' AND COLUMN_TYPE='varchar(30)' AND IS_NULLABLE='NO') OR
     (COLUMN_NAME IN ('ENABLED','MUST_CHANGE_PASSWORD') AND COLUMN_TYPE='tinyint(1)') OR
     (COLUMN_NAME='PASSWORD_CHANGED_AT' AND COLUMN_TYPE='datetime(6)' AND IS_NULLABLE='YES'));
  IF n<>6 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Preflight: columnas no compatibles'; END IF;
  IF (SELECT COUNT(*) FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA='auxiliares')<>11 THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Preflight: se esperaban 11 triggers';
  END IF;
  IF EXISTS(SELECT 1 FROM information_schema.TABLES WHERE TABLE_SCHEMA='auxiliares' AND
    ((TABLE_NAME='TP_ADMIN_ROLES_V1_STATE' AND TABLE_COMMENT<>'territorio-paysandu roles-v1 state') OR
     (TABLE_NAME='TP_ADMIN_ROLES_V1_USERS' AND TABLE_COMMENT<>'territorio-paysandu roles-v1 baseline') OR
     (TABLE_NAME='TP_ADMIN_ROLES_V1_TRIGGERS' AND TABLE_COMMENT<>'territorio-paysandu roles-v1 trigger fingerprints'))) THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Colision de tablas de migracion; no continuar';
  END IF;
  -- IF NOT EXISTS no valida contratos: comentarios/nombres se revisan en 00-preflight.
  -- Nunca reutilizar tablas preexistentes ajenas; conservar estas tablas para recuperación.
  CREATE TABLE IF NOT EXISTS TP_ADMIN_ROLES_V1_STATE (
    ID TINYINT PRIMARY KEY, PHASE VARCHAR(30) NOT NULL,
    CREDENTIAL_COUNT BIGINT NOT NULL, SESSION_COUNT BIGINT NOT NULL,
    CREATED_AT DATETIME(6) NOT NULL,
    CONSTRAINT CHK_TP_ADMIN_ROLES_V1_ID CHECK(ID=1)
  ) ENGINE=InnoDB COMMENT='territorio-paysandu roles-v1 state';
  CREATE TABLE IF NOT EXISTS TP_ADMIN_ROLES_V1_USERS (
    USER_ID CHAR(36) PRIMARY KEY, ORIGINAL_ROLE VARCHAR(30) NOT NULL,
    ORIGINAL_ENABLED TINYINT(1), ORIGINAL_MUST_CHANGE_PASSWORD TINYINT(1),
    ORIGINAL_PASSWORD_CHANGED_AT DATETIME(6)
  ) ENGINE=InnoDB COMMENT='territorio-paysandu roles-v1 baseline';
  CREATE TABLE IF NOT EXISTS TP_ADMIN_ROLES_V1_TRIGGERS (
    TRIGGER_NAME VARCHAR(64) PRIMARY KEY, DEFINITION_HASH CHAR(64) NOT NULL
  ) ENGINE=InnoDB COMMENT='territorio-paysandu roles-v1 trigger fingerprints';
  IF NOT EXISTS(SELECT 1 FROM TP_ADMIN_ROLES_V1_STATE WHERE ID=1) THEN
    IF (SELECT COUNT(*) FROM FB_USUARIOS)<>10 OR
       (SELECT COUNT(*) FROM FB_USUARIOS WHERE ROLE='collaborator' AND ENABLED=1)<>10 OR
       (SELECT COUNT(*) FROM FB_USUARIOS WHERE MUST_CHANGE_PASSWORD=1)<>9 OR
       (SELECT COUNT(*) FROM FB_USUARIOS WHERE MUST_CHANGE_PASSWORD=0)<>1 OR
       (SELECT COUNT(*) FROM FB_CIU_CONSULTAS_WEB)<>0 OR (SELECT COUNT(*) FROM FB_CONSULTAS_HISTORIAL)<>0 OR
       (SELECT COUNT(*) FROM TP_ADMIN_ROLES_V1_USERS)<>0 OR (SELECT COUNT(*) FROM TP_ADMIN_ROLES_V1_TRIGGERS)<>0 THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Estado inicial difiere de los 10 usuarios confirmados';
    END IF;
    IF NOT EXISTS(SELECT 1 FROM information_schema.CHECK_CONSTRAINTS
      WHERE CONSTRAINT_SCHEMA='auxiliares' AND TABLE_NAME='FB_USUARIOS' AND CONSTRAINT_NAME='CHK_FB_USUARIOS_ROLE'
      AND LOWER(REPLACE(REPLACE(REPLACE(REPLACE(CHECK_CLAUSE,'`',''),' ',''),'(',''),')','')) IN ('role=''collaborator''','''collaborator''=role')) THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='CHECK original desconocido: revisar manualmente';
    END IF;
    START TRANSACTION;
    INSERT INTO TP_ADMIN_ROLES_V1_USERS SELECT USER_ID,ROLE,ENABLED,MUST_CHANGE_PASSWORD,PASSWORD_CHANGED_AT FROM FB_USUARIOS;
    INSERT INTO TP_ADMIN_ROLES_V1_TRIGGERS SELECT TRIGGER_NAME,
      SHA2(CONCAT_WS('|',EVENT_OBJECT_TABLE,ACTION_TIMING,EVENT_MANIPULATION,ACTION_STATEMENT,ACTION_ORDER,SQL_MODE,DEFINER,CHARACTER_SET_CLIENT,COLLATION_CONNECTION,DATABASE_COLLATION),256)
      FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA='auxiliares';
    INSERT INTO TP_ADMIN_ROLES_V1_STATE VALUES(1,'captured',
      (SELECT COUNT(*) FROM FB_USUARIOS_CREDENCIALES),(SELECT COUNT(*) FROM FB_USUARIOS_SESIONES),UTC_TIMESTAMP(6));
    COMMIT;
  END IF;
  IF (SELECT PHASE FROM TP_ADMIN_ROLES_V1_STATE WHERE ID=1)='rolled-back' THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Rollback previo: requiere nuevo plan, no reaplicar';
  END IF;
  -- Un solo ALTER evita dejar la restricción ausente entre sentencias.
  -- DDL hace commits implícitos. Captured permite reanudar después de caída.
  IF (SELECT PHASE FROM TP_ADMIN_ROLES_V1_STATE WHERE ID=1)='captured' THEN
    ALTER TABLE FB_USUARIOS
      DROP CONSTRAINT CHK_FB_USUARIOS_ROLE,
      ADD CONSTRAINT CHK_FB_USUARIOS_ROLE CHECK(ROLE IN ('atencion_publico','collaborator','administrator')),
      ALTER COLUMN ROLE SET DEFAULT 'atencion_publico';
    UPDATE TP_ADMIN_ROLES_V1_STATE SET PHASE='expanded' WHERE ID=1;
    COMMIT;
  END IF;
END//
DELIMITER ;
