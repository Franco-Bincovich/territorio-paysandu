-- SOLO LECTURA, NO EJECUTADO. Todas las diferencias deben ser cero antes de iniciar app.
USE auxiliares;
SELECT PHASE,CREATED_AT FROM TP_ADMIN_ROLES_V1_STATE WHERE ID=1;
SELECT ROLE,COUNT(*) AS total FROM FB_USUARIOS GROUP BY ROLE;
SELECT COUNT(*) AS baseline_differences FROM TP_ADMIN_ROLES_V1_USERS b
 LEFT JOIN FB_USUARIOS u ON u.USER_ID=b.USER_ID
 WHERE u.USER_ID IS NULL OR u.ROLE<>'atencion_publico'
 OR NOT(u.ENABLED<=>b.ORIGINAL_ENABLED)
 OR NOT(u.MUST_CHANGE_PASSWORD<=>b.ORIGINAL_MUST_CHANGE_PASSWORD)
 OR NOT(u.PASSWORD_CHANGED_AT<=>b.ORIGINAL_PASSWORD_CHANGED_AT)
 OR u.DELETED_AT IS NOT NULL OR u.ADMIN_REVISION<>1;
SELECT (SELECT COUNT(*) FROM FB_USUARIOS)-10 AS user_count_difference,
 (SELECT COUNT(*) FROM FB_USUARIOS_CREDENCIALES)-CREDENTIAL_COUNT AS credential_count_difference,
 (SELECT COUNT(*) FROM FB_USUARIOS_SESIONES)-SESSION_COUNT AS session_count_difference,
 (SELECT COUNT(*) FROM FB_CIU_CONSULTAS_WEB) AS consultations,
 (SELECT COUNT(*) FROM FB_CONSULTAS_HISTORIAL) AS histories
 FROM TP_ADMIN_ROLES_V1_STATE WHERE ID=1;
SELECT COUNT(*) AS changed_or_missing_triggers FROM TP_ADMIN_ROLES_V1_TRIGGERS b
 LEFT JOIN information_schema.TRIGGERS t ON t.TRIGGER_SCHEMA='auxiliares' AND t.TRIGGER_NAME=b.TRIGGER_NAME
 WHERE t.TRIGGER_NAME IS NULL OR b.DEFINITION_HASH<>SHA2(CONCAT_WS('|',t.EVENT_OBJECT_TABLE,t.ACTION_TIMING,t.EVENT_MANIPULATION,t.ACTION_STATEMENT,t.ACTION_ORDER,t.SQL_MODE,t.DEFINER,t.CHARACTER_SET_CLIENT,t.COLLATION_CONNECTION,t.DATABASE_COLLATION),256);
SELECT COUNT(*) AS extra_triggers FROM information_schema.TRIGGERS t
 LEFT JOIN TP_ADMIN_ROLES_V1_TRIGGERS b ON b.TRIGGER_NAME=t.TRIGGER_NAME
 WHERE t.TRIGGER_SCHEMA='auxiliares' AND b.TRIGGER_NAME IS NULL;
SELECT COLUMN_NAME,COLUMN_TYPE,COLUMN_DEFAULT,IS_NULLABLE FROM information_schema.COLUMNS
 WHERE TABLE_SCHEMA='auxiliares' AND TABLE_NAME='FB_USUARIOS' AND COLUMN_NAME IN ('ROLE','ADMIN_REVISION','DELETED_AT');
SELECT CONSTRAINT_NAME,CHECK_CLAUSE FROM information_schema.CHECK_CONSTRAINTS
 WHERE CONSTRAINT_SCHEMA='auxiliares' AND TABLE_NAME='FB_USUARIOS';
SHOW CREATE TABLE TP_ADMIN_AUDIT_V1;
-- Esperado: migrated, 10 atencion_publico, default atencion_publico, 3 roles en CHECK,
-- 9 cambios obligatorios preservados, cero diferencias; auditoría vacía antes del bootstrap.
SELECT COUNT(*) AS audit_events FROM TP_ADMIN_AUDIT_V1;
