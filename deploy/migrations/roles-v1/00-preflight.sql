SELECT VERSION() AS version, DATABASE() AS current_database;
SHOW CREATE TABLE auxiliares.FB_USUARIOS;
SHOW CREATE TABLE auxiliares.FB_USUARIOS_CREDENCIALES;
SHOW CREATE TABLE auxiliares.FB_USUARIOS_SESIONES;
SELECT TABLE_NAME, ENGINE, TABLE_COLLATION FROM information_schema.TABLES
 WHERE TABLE_SCHEMA='auxiliares' AND TABLE_NAME IN
 ('FB_USUARIOS','FB_USUARIOS_CREDENCIALES','FB_USUARIOS_SESIONES','FB_LOGIN_INTENTOS','FB_SECURITY_STANDALONE_V1','FB_CIU_CONSULTAS_WEB','FB_CONSULTAS_HISTORIAL');
SELECT COLUMN_NAME,COLUMN_TYPE,IS_NULLABLE,COLUMN_DEFAULT,EXTRA FROM information_schema.COLUMNS
 WHERE TABLE_SCHEMA='auxiliares' AND TABLE_NAME='FB_USUARIOS' ORDER BY ORDINAL_POSITION;
SELECT CONSTRAINT_NAME,CHECK_CLAUSE FROM information_schema.CHECK_CONSTRAINTS
 WHERE CONSTRAINT_SCHEMA='auxiliares' AND TABLE_NAME='FB_USUARIOS';
SELECT ROLE,ENABLED,MUST_CHANGE_PASSWORD,COUNT(*) AS total FROM auxiliares.FB_USUARIOS
 GROUP BY ROLE,ENABLED,MUST_CHANGE_PASSWORD;
SELECT (SELECT COUNT(*) FROM auxiliares.FB_USUARIOS) AS users,
 (SELECT COUNT(*) FROM auxiliares.FB_USUARIOS_CREDENCIALES) AS credentials,
 (SELECT COUNT(*) FROM auxiliares.FB_USUARIOS_SESIONES) AS sessions,
 (SELECT COUNT(*) FROM auxiliares.FB_CIU_CONSULTAS_WEB) AS consultations,
 (SELECT COUNT(*) FROM auxiliares.FB_CONSULTAS_HISTORIAL) AS histories;
SELECT TRIGGER_NAME,EVENT_OBJECT_TABLE,ACTION_TIMING,EVENT_MANIPULATION,ACTION_STATEMENT
 FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA='auxiliares' ORDER BY TRIGGER_NAME;
SELECT TABLE_NAME,CONSTRAINT_NAME,COLUMN_NAME,REFERENCED_TABLE_NAME,REFERENCED_COLUMN_NAME
 FROM information_schema.KEY_COLUMN_USAGE WHERE TABLE_SCHEMA='auxiliares'
 AND (TABLE_NAME='FB_USUARIOS' OR REFERENCED_TABLE_NAME='FB_USUARIOS');
