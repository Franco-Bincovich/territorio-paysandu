-- BORRADOR NO EJECUTADO. Solo remapea los IDs de la instantánea inicial.
-- No ejecutar con aplicación/otros escritores activos. No modifica credenciales.
USE auxiliares;
DELIMITER //
BEGIN NOT ATOMIC
  DECLARE changed_rows INT DEFAULT 0;
  DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;
  IF COALESCE(@tp_roles_v1_approved,0)<>1 OR
     NOT EXISTS(SELECT 1 FROM TP_ADMIN_ROLES_V1_STATE WHERE ID=1 AND PHASE IN ('admin-ready','migrated')) THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Falta preparacion aprobada';
  END IF;
  IF (SELECT COUNT(*) FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA='auxiliares')<>11 OR
     (SELECT COUNT(*) FROM TP_ADMIN_ROLES_V1_TRIGGERS)<>11 OR
     EXISTS(SELECT 1 FROM TP_ADMIN_ROLES_V1_TRIGGERS b LEFT JOIN information_schema.TRIGGERS t
       ON t.TRIGGER_SCHEMA='auxiliares' AND t.TRIGGER_NAME=b.TRIGGER_NAME
       WHERE t.TRIGGER_NAME IS NULL OR b.DEFINITION_HASH<>SHA2(CONCAT_WS('|',t.EVENT_OBJECT_TABLE,t.ACTION_TIMING,t.EVENT_MANIPULATION,t.ACTION_STATEMENT,t.ACTION_ORDER,t.SQL_MODE,t.DEFINER,t.CHARACTER_SET_CLIENT,t.COLLATION_CONNECTION,t.DATABASE_COLLATION),256)) THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Triggers cambiaron: no ejecutar DML';
  END IF;
  IF (SELECT PHASE FROM TP_ADMIN_ROLES_V1_STATE WHERE ID=1)='admin-ready' THEN
    START TRANSACTION;
    -- Los escritores están detenidos; todos deben usar el mutex al integrar administración.
    IF (SELECT COUNT(*) FROM FB_USUARIOS)<>10 OR (SELECT COUNT(*) FROM TP_ADMIN_ROLES_V1_USERS)<>10 OR
       (SELECT COUNT(*) FROM FB_USUARIOS u JOIN TP_ADMIN_ROLES_V1_USERS b ON b.USER_ID=u.USER_ID
         WHERE u.ROLE=b.ORIGINAL_ROLE AND u.ENABLED<=>b.ORIGINAL_ENABLED
         AND u.MUST_CHANGE_PASSWORD<=>b.ORIGINAL_MUST_CHANGE_PASSWORD
         AND u.PASSWORD_CHANGED_AT<=>b.ORIGINAL_PASSWORD_CHANGED_AT
         AND u.ADMIN_REVISION=1 AND u.DELETED_AT IS NULL)<>10 OR
       (SELECT COUNT(*) FROM FB_USUARIOS_SESIONES)<>(SELECT SESSION_COUNT FROM TP_ADMIN_ROLES_V1_STATE WHERE ID=1) OR
       (SELECT COUNT(*) FROM FB_USUARIOS_CREDENCIALES)<>(SELECT CREDENTIAL_COUNT FROM TP_ADMIN_ROLES_V1_STATE WHERE ID=1) OR
       (SELECT COUNT(*) FROM FB_CIU_CONSULTAS_WEB)<>0 OR (SELECT COUNT(*) FROM FB_CONSULTAS_HISTORIAL)<>0 THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Estado cambio desde snapshot; no migrar';
    END IF;
    UPDATE FB_USUARIOS u JOIN TP_ADMIN_ROLES_V1_USERS b ON b.USER_ID=u.USER_ID
      SET u.ROLE='atencion_publico' WHERE b.ORIGINAL_ROLE='collaborator' AND u.ROLE='collaborator';
    SET changed_rows=ROW_COUNT();
    IF changed_rows<>10 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Se esperaban exactamente 10 roles migrados'; END IF;
    UPDATE TP_ADMIN_ROLES_V1_STATE SET PHASE='migrated' WHERE ID=1;
    COMMIT;
  END IF;
  -- Repetir después de migrated no remapea futuros colaboradores legítimos.
END//
DELIMITER ;
