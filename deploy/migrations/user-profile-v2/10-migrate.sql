-- DBA only with application stopped. DDL autocommits; backup before running.
USE auxiliares;
DELIMITER $$
CREATE PROCEDURE TP_PROFILE_V2_MIGRATE()
BEGIN
 IF EXISTS(SELECT 1 FROM FB_USUARIOS WHERE DELETED_AT IS NULL AND (BINARY USERNAME REGEXP '[^ -~]' OR BINARY USERNAME<>BINARY TRIM(USERNAME))) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Review canonical keys for non-ASCII or padded usernames before migration'; END IF;
 IF EXISTS(SELECT 1 FROM (SELECT COUNT(*) AS n FROM FB_USUARIOS WHERE DELETED_AT IS NULL GROUP BY BINARY LOWER(TRIM(USERNAME)) HAVING COUNT(*)>1) AS conflicts) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Resolve canonical username conflicts before migration'; END IF;
 ALTER TABLE FB_USUARIOS ADD FIRST_NAME VARCHAR(100) NULL, ADD LAST_NAME VARCHAR(100) NULL, ADD EMAIL VARCHAR(254) NULL, ADD CI VARCHAR(8) NULL, ADD USERNAME_KEY VARBINARY(400) NULL, ADD EMAIL_KEY VARBINARY(1016) NULL;
 UPDATE FB_USUARIOS SET USERNAME_KEY=IF(DELETED_AT IS NULL,CONVERT(LOWER(TRIM(USERNAME)) USING binary),NULL);
 ALTER TABLE FB_USUARIOS ADD UNIQUE KEY UK_PROFILE_USERNAME_KEY(USERNAME_KEY),ADD UNIQUE KEY UK_PROFILE_EMAIL_KEY(EMAIL_KEY);
 -- Release old display-name uniqueness only after canonical uniqueness exists.
 BEGIN
  DECLARE finished INT DEFAULT 0; DECLARE index_name_value VARCHAR(64);
  DECLARE indexes_cursor CURSOR FOR SELECT INDEX_NAME FROM information_schema.STATISTICS WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='FB_USUARIOS' AND NON_UNIQUE=0 GROUP BY INDEX_NAME HAVING GROUP_CONCAT(COLUMN_NAME ORDER BY SEQ_IN_INDEX)='USERNAME';
  DECLARE CONTINUE HANDLER FOR NOT FOUND SET finished=1;
  OPEN indexes_cursor;
  index_loop: LOOP
   FETCH indexes_cursor INTO index_name_value;
   IF finished=1 THEN LEAVE index_loop; END IF;
   SET @profile_sql=CONCAT('ALTER TABLE FB_USUARIOS DROP INDEX `',REPLACE(index_name_value,'`','``'),'`');PREPARE profile_statement FROM @profile_sql;EXECUTE profile_statement;DEALLOCATE PREPARE profile_statement;
  END LOOP;
  CLOSE indexes_cursor;
 END;
 ALTER TABLE TP_ADMIN_AUDIT_V1 ADD ACTOR_USERNAME VARCHAR(100) NULL,ADD TARGET_USERNAME VARCHAR(100) NULL;
END$$
DELIMITER ;
CALL TP_PROFILE_V2_MIGRATE();
DROP PROCEDURE TP_PROFILE_V2_MIGRATE;
