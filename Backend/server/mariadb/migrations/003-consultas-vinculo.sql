USE auxiliares;
DELIMITER $$
BEGIN NOT ATOMIC
  IF COALESCE((SELECT REVISION FROM FB_MODELO_REVISION WHERE MODELO='consultas'),'') NOT IN ('7.1','7.2') THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Se requiere el modelo de consultas 7.1 o 7.2';
  END IF;
  IF EXISTS (
    SELECT 1 FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME IN ('FB_CIU_CONSULTAS_WEB','FB_CONSULTAS_HISTORIAL')
      AND COLUMN_NAME='RELACION_OTRO_DETALLE'
      AND (COLUMN_TYPE <> 'varchar(100)' OR IS_NULLABLE <> 'YES' OR EXTRA <> ''
        OR COLLATION_NAME <> 'utf8mb4_unicode_ci' OR NOT (COLUMN_DEFAULT <=> 'NULL'))
  ) THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Definición inesperada de RELACION_OTRO_DETALLE';
  END IF;
  -- Acepta los cuerpos 7.1 y 7.2 para poder reanudar una migración parcial.
  IF (SELECT COUNT(*) FROM information_schema.TRIGGERS
      WHERE TRIGGER_SCHEMA=DATABASE() AND EVENT_OBJECT_TABLE='FB_CIU_CONSULTAS_WEB'
        AND ((TRIGGER_NAME='TRG_FB_CONSULTAS_VERSION' AND SHA2(REPLACE(ACTION_STATEMENT,CHAR(13),''),256)
            IN ('4be4ff341c0d2c8967f7985a96bcaf3942db6c43379747d8f506f71687bbe327',
                'daa8d067645d524fc8bbb94fff17b9438d5e94badb1bba96f20055fa385db13d'))
          OR (TRIGGER_NAME='TRG_FB_CONSULTAS_HIST_ALTA' AND SHA2(REPLACE(ACTION_STATEMENT,CHAR(13),''),256)
            IN ('ce2c9e18dc0da7709ad1735f891c390fdd15174f699f29b85b7924c5e4cd149f',
                'd0789fb9c51b0e849c54ffa0df93016cc93f151f18d62618794880c48f2c2619'))
          OR (TRIGGER_NAME='TRG_FB_CONSULTAS_HIST_UPDATE' AND SHA2(REPLACE(ACTION_STATEMENT,CHAR(13),''),256)
            IN ('9bff2ba5668204256352beda8a166936ff8d268b58fbb68794dd2bba4c411f3a',
                'f17608818100b39053866a3b095b7754a30a55048e34e5e66e47eecd47630fbd')))) <> 3 THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Revisar las definiciones locales de los triggers de consultas';
  END IF;
END$$

