USE auxiliares;
CREATE TABLE FB_CONSULTAS_IDEMPOTENCIA (
 USUARIO_ID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 CLAVE CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 PAYLOAD_HASH CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 RESERVA_TOKEN CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 ID_CONSULTA BIGINT NULL, RESPUESTA_JSON JSON NULL,
 FECHA_ALTA DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 PRIMARY KEY (USUARIO_ID,CLAVE),
 CONSTRAINT FK_71_RECEIPT_ACTOR FOREIGN KEY (USUARIO_ID) REFERENCES FB_USUARIOS(USER_ID),
 CONSTRAINT FK_71_RECEIPT_QUERY FOREIGN KEY (ID_CONSULTA) REFERENCES FB_CIU_CONSULTAS_WEB(ID_CONSULTA),
 CONSTRAINT CHK_71_RECEIPT_COMPLETO CHECK ((ID_CONSULTA IS NULL AND RESPUESTA_JSON IS NULL) OR (ID_CONSULTA IS NOT NULL AND RESPUESTA_JSON IS NOT NULL))
) ENGINE=InnoDB;
